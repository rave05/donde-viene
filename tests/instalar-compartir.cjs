const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const source = fs.readFileSync('instalar-compartir.js','utf8');
function setup({ua='',standalone=false,hidden=false,storageFails=false}={}) {
  const dom = new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://example.test/donde-viene/?origen=Casa#viaje=secreto',runScripts:'outside-only'});
  const w = dom.window, d = w.document;
  let listener;
  w.matchMedia = () => ({matches:standalone,addEventListener:(_,cb)=>{listener=cb;}});
  Object.defineProperty(w.navigator,'userAgent',{value:ua});
  w.HTMLDialogElement.prototype.showModal = function(){this.open=true;};
  w.HTMLDialogElement.prototype.close = function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
  if(hidden) w.localStorage.setItem('donde-viene:ocultar-instalacion','1');
  if(storageFails) {w.Storage.prototype.getItem=()=>{throw Error('blocked');};w.Storage.prototype.setItem=()=>{throw Error('blocked');};}
  w.eval(source);
  return {w,d,dom,mode:(matches)=>listener({matches}),click:id=>d.getElementById(id).click()};
}
const tick = () => new Promise(r=>setImmediate(r));
(async()=>{
  const a=setup({ua:'iPhone'});
  assert.equal(a.d.getElementById('avisoInstalacion').hidden,false);
  a.click('btnAyudaInstalacion');
  assert.match(a.d.getElementById('pasosInstalacion').textContent,/Safari/);
  assert.match(a.d.getElementById('pasosInstalacion').textContent,/Editar acciones/);
  a.click('btnCerrarInstalacion');assert.equal(a.d.getElementById('ayudaInstalacion').open,false);
  a.click('btnOcultarInstalacion');assert.equal(a.d.getElementById('avisoInstalacion').hidden,true);
  assert.equal(a.w.localStorage.getItem('donde-viene:ocultar-instalacion'),'1');
  a.click('btnReabrirInstalacion');assert.equal(a.d.getElementById('avisoInstalacion').hidden,false);
  let payload;
  a.w.navigator.share=async data=>{payload=data;};
  a.click('btnCompartirApp');await tick();
  assert.equal(payload.url,'https://example.test/donde-viene/');
  assert.doesNotMatch(JSON.stringify(payload),/Casa|secreto|viaje=/);
  a.w.navigator.share=async()=>{throw new a.w.DOMException('cancelled','AbortError');};
  a.click('btnCompartirApp');await tick();
  assert.equal(a.d.getElementById('enlaceCompartirApp').hidden,true);
  assert.equal(a.d.getElementById('estadoCompartirApp').textContent,'');
  delete a.w.navigator.share;
  let copied;
  a.w.navigator.clipboard={writeText:async text=>{copied=text;}};
  a.click('btnCompartirApp');await tick();assert.equal(copied,payload.url);
  a.w.navigator.clipboard.writeText=async()=>{throw Error('denied');};
  a.click('btnCompartirApp');await tick();assert.equal(a.d.getElementById('enlaceCompartirApp').value,payload.url);
  assert.equal(a.d.getElementById('enlaceCompartirApp').hidden,false);
  a.dom.window.close();
  const b=setup({ua:'Android',hidden:true});
  assert.equal(b.d.getElementById('avisoInstalacion').hidden,true);
  b.click('btnReabrirInstalacion'); b.click('btnAyudaInstalacion');
  assert.match(b.d.getElementById('pasosInstalacion').textContent,/menú del navegador/);
  b.click('btnCerrarInstalacion');
  let count=0;
  const prompt=new b.w.Event('beforeinstallprompt',{cancelable:true});
  prompt.prompt=async()=>{count++;};prompt.userChoice=Promise.resolve({outcome:'dismissed'});
  b.w.dispatchEvent(prompt);assert.equal(prompt.defaultPrevented,true);assert.equal(count,0);
  assert.equal(b.d.getElementById('avisoInstalacion').hidden,false);
  b.click('btnAyudaInstalacion');b.click('btnAyudaInstalacion');await tick();assert.equal(count,1);
  b.click('btnAyudaInstalacion');assert.equal(count,1);assert.equal(b.d.getElementById('ayudaInstalacion').open,true);
  b.w.dispatchEvent(new b.w.Event('appinstalled'));assert.equal(b.d.getElementById('btnAyudaInstalacion').hidden,true);
  assert.equal(b.d.getElementById('btnCompartirApp').hidden,false);b.dom.window.close();
  const c=setup({standalone:true});assert.equal(c.d.getElementById('avisoInstalacion').hidden,true);
  c.click('btnReabrirInstalacion');assert.equal(c.d.getElementById('btnAyudaInstalacion').hidden,true);
  assert.equal(c.d.getElementById('btnCompartirApp').hidden,false);c.dom.window.close();
  const e=setup({storageFails:true});e.click('btnOcultarInstalacion');assert.equal(e.d.getElementById('avisoInstalacion').hidden,true);
  e.click('btnReabrirInstalacion');assert.equal(e.d.getElementById('avisoInstalacion').hidden,false);e.dom.window.close();
  console.log('Instalar y compartir: iOS/Android, prompt único, cierre, reapertura, app instalada, enlace sin direcciones, copia y cancelación OK');
})().catch(error=>{console.error(error);process.exitCode=1;});
